package authhttp

// #328: the route table in docs/api-endpoints.md is generated from the route
// registry. `go test ./authhttp -run TestAPIEndpointsDoc -update` rewrites
// the block between the markers; the test fails when the committed block is
// stale, so the table cannot drift from the code again.

import (
	"crypto"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
	"time"

	authkit "github.com/open-rails/authkit"
	"github.com/open-rails/authkit/authprovider"
	"github.com/open-rails/authkit/embedded"
	authcore "github.com/open-rails/authkit/internal/authcore"
	"github.com/open-rails/authkit/jwtkit"
	"github.com/stretchr/testify/require"
)

var updateRouteDoc = flag.Bool("update", false, "rewrite the generated route table in docs/api-endpoints.md")

const (
	routeDocPath  = "../docs/api-endpoints.md"
	routeDocBegin = "<!-- routes:begin — generated by `go test ./authhttp -run TestAPIEndpointsDoc -update`; do not edit by hand -->"
	routeDocEnd   = "<!-- routes:end -->"
)

// docService is a DB-free Service with every optional surface enabled, so the
// registry lists the whole route table.
func docService(t *testing.T) *Service {
	t.Helper()
	signer, err := jwtkit.NewRSASigner(2048, "doc")
	require.NoError(t, err)
	ks := authcore.Keyset{Active: signer, PublicKeys: map[string]crypto.PublicKey{"doc": signer.PublicKey()}}
	cfg := embedded.Config{
		Token:     embedded.TokenConfig{Issuer: "https://example.com", IssuedAudiences: []string{"app"}, ExpectedAudiences: []string{"app"}, AccessTokenDuration: time.Hour},
		Frontend:  embedded.FrontendConfig{BaseURL: "https://example.com"},
		Ephemeral: embedded.EphemeralConfig{AllowMemory: true},
		Registration: embedded.RegistrationConfig{
			Verification:      embedded.RegistrationVerificationNone,
			NativeUserMode:    authkit.RegistrationModeOpen,
			PasswordlessLogin: true,
		},
		TwoFactor:     embedded.TwoFactorConfig{Mode: authkit.TwoFactorMode("optional")},
		Passkeys:      embedded.PasskeyConfig{RPID: "example.com", RPDisplayName: "Example", Origins: []string{"https://example.com"}},
		DeviceKeys:    embedded.DeviceKeysConfig{Enabled: true},
		SolanaNetwork: "devnet",
		Identity:      embedded.IdentityConfig{Providers: []authprovider.Provider{authprovider.Google("client-id", "client-secret")}},
		Applications:  embedded.ApplicationsConfig{SelfRegistration: true, OrgPersona: "org"},
		Delegated:     embedded.DelegatedConfig{Audiences: []string{"app"}},
		RBAC: []embedded.PersonaDef{{
			Name:         "org",
			Parent:       authkit.RootPersona,
			Capabilities: authkit.PersonaCapabilities{APIKeys: true, RemoteApplications: true, CustomRoles: true},
			Creation:     authkit.InstanceCreationDef{Enabled: true},
		}},
	}
	core, err := authcore.NewService(cfg, ks, depsOf())
	require.NoError(t, err)
	s := serviceFromCore(t, core)
	providers, err := providerRegistry(cfg.Identity.Providers)
	require.NoError(t, err)
	s.providers = providers
	return s
}

type routeDocRow struct {
	Method, Path, Group, Auth, Bucket, Requires string
}

func routeDocAuth(r RouteSpec) string {
	switch r.Auth {
	case AuthPermission:
		return string("`" + r.Permission + "`")
	case AuthSigned:
		return "signed request (domain proof)"
	case "":
		return "public"
	}
	return string(r.Auth)
}

var routeDocGroupOrder = map[RouteGroup]int{
	"root": 0, RouteAuth: 1, RouteRegistration: 2, RouteAccount: 3, RouteDeviceKeys: 4, RouteBrowserOIDC: 5,
	RouteDelegated: 6, RouteDocuments: 7, RouteApplications: 8, RouteAdmin: 9, RoutePermissionGroups: 10,
}

func routeDocRows(s *Service) []routeDocRow {
	rows := []routeDocRow{
		{"GET", JWKSPath, "root", "public", "", ""},
		{"GET, HEAD", DocumentsPath, "root", "reader application (`Documents.Readers`)", "", "WithDocuments"},
	}
	for _, r := range s.APIRoutes() {
		rows = append(rows, routeDocRow{r.Method, "{api}" + r.Path, string(r.Group), routeDocAuth(r), r.Bucket, r.Requires()})
	}
	for _, r := range s.OIDCBrowserRoutes() {
		rows = append(rows, routeDocRow{r.Method, "{oidc}" + r.Path, string(r.Group), routeDocAuth(r), r.Bucket, r.Requires()})
	}
	sort.SliceStable(rows, func(i, j int) bool {
		a, b := rows[i], rows[j]
		if ga, gb := routeDocGroupOrder[RouteGroup(a.Group)], routeDocGroupOrder[RouteGroup(b.Group)]; ga != gb {
			return ga < gb
		}
		if a.Path != b.Path {
			return a.Path < b.Path
		}
		return a.Method < b.Method
	})
	return rows
}

func renderRouteDoc(rows []routeDocRow) string {
	var b strings.Builder
	b.WriteString("`{api}` is the mount's `APIPrefix` (default `/api/v1`); `{oidc}` is `/oidc`. Bucket = the per-IP rate-limit bucket the registry applies before the handler (per-identifier and branch buckets live in the handler). Mounted when = the configuration that enables the route (blank = always).\n\n")
	b.WriteString("| Method | Path | Group | Auth | Bucket | Mounted when |\n|---|---|---|---|---|---|\n")
	for _, r := range rows {
		bucket := r.Bucket
		if bucket != "" {
			bucket = "`" + bucket + "`"
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s |\n", r.Method, r.Path, r.Group, r.Auth, bucket, r.Requires)
	}
	return b.String()
}

func TestAPIEndpointsDoc(t *testing.T) {
	rendered := renderRouteDoc(routeDocRows(docService(t)))
	raw, err := os.ReadFile(routeDocPath)
	require.NoError(t, err)
	doc := string(raw)
	i, j := strings.Index(doc, routeDocBegin), strings.Index(doc, routeDocEnd)
	require.True(t, i >= 0 && j > i, "docs/api-endpoints.md must contain the routes:begin/routes:end markers")
	i += len(routeDocBegin)
	if *updateRouteDoc {
		require.NoError(t, os.WriteFile(routeDocPath, []byte(doc[:i]+"\n"+rendered+doc[j:]), 0o644))
		return
	}
	require.Equal(t, "\n"+rendered, doc[i:j], "docs/api-endpoints.md route table is stale: run `go test ./authhttp -run TestAPIEndpointsDoc -update`")
}
