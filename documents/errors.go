	ErrInvalidReference     = errmodel.E(CodeInvalidReference)
	ErrInvalidType          = errmodel.E(CodeInvalidType)
	ErrInvalidDigest        = errmodel.E(CodeInvalidDigest)
	ErrDuplicateReference   = errmodel.E(CodeDuplicateReference)
	ErrTooManyReferences    = errmodel.E(CodeTooManyReferences)
	ErrReferencesTooLarge   = errmodel.E(CodeReferencesTooLarge)
	ErrWrongTokenType       = errmodel.E(CodeWrongTokenType)
