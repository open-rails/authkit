package main

import (
	"bytes"
	"fmt"
	"reflect"
	"strings"

	"github.com/open-rails/authkit/internal/errmodel"
)

const tsHeader = "// Generated by `go generate ./internal/httpapi` from AuthKit's route catalog. Do not edit.\n"

// tsType is t as a TypeScript type.
func tsType(t reflect.Type) string {
	switch classify(t) {
	case kindString:
		if values := enumValues(t); values != nil {
			quoted := make([]string, len(values))
			for i, v := range values {
				quoted[i] = fmt.Sprintf("%q", v)
			}
			return strings.Join(quoted, " | ")
		}
		return "string"
	case kindTime, kindBytes:
		return "string"
	case kindInteger, kindNumber:
		return "number"
	case kindBoolean:
		return "boolean"
	case kindAny:
		return "unknown"
	case kindOpaque:
		return "Record<string, unknown>"
	case kindArray:
		return tsElem(t.Elem()) + "[]"
	case kindMap:
		return "Record<string, " + tsType(t.Elem()) + ">"
	case kindNullable:
		return tsType(t.Elem()) + " | null"
	case kindPage:
		return "ListPage<" + tsType(pageItem(t)) + ">"
	}
	return wireName(t)
}

// tsElem parenthesizes a union element type.
func tsElem(t reflect.Type) string {
	s := tsType(t)
	if strings.Contains(s, " | ") {
		return "(" + s + ")"
	}
	return s
}

// wireTS is every wire type. Responses are exact: every member present, null
// when unset. Request members are optional: the server reads an omitted one
// as empty.
func (c *contract) wireTS() []byte {
	var b bytes.Buffer
	b.WriteString(tsHeader)
	b.WriteString(`
// One page of a list: next_cursor is null on the last page, total is null
// unless the list was asked to count.
export type ListPage<T> = {
  data: T[]
  next_cursor: string | null
  total: number | null
}
`)
	for _, o := range c.sortedObjects() {
		fmt.Fprintf(&b, "\nexport type %s = {\n", o.name)
		for _, f := range o.fields {
			opt := ""
			if o.input && !o.output || f.optional {
				opt = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s\n", tsKey(f.name), opt, tsType(f.t))
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

func tsKey(name string) string {
	for _, r := range name {
		if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			return fmt.Sprintf("%q", name)
		}
	}
	if name != "" && name[0] >= '0' && name[0] <= '9' {
		return fmt.Sprintf("%q", name)
	}
	return name
}

// routesTS is the route catalog on a default mount.
func (c *contract) routesTS() []byte {
	var b bytes.Buffer
	b.WriteString(tsHeader)
	b.WriteString(`
export type AuthKitRoute = {
  method: string
  // The path on a default mount (API beneath /api/v1, browser OIDC beneath /oidc).
  path: string
  group: string
  auth: "public" | "optional" | "required" | "session" | "permission"
  permission: string | null
  // The caller must have signed in recently (step_up_required otherwise).
  stepUp: boolean
  // The configuration the route needs; null when always mounted.
  mountedWhen: string | null
}

export const AUTHKIT_ROUTES: readonly AuthKitRoute[] = [
`)
	for _, r := range c.routes {
		perm, when := "null", "null"
		if r.Perm != "" {
			perm = fmt.Sprintf("%q", r.Perm)
		}
		if r.MountedWhen != "" {
			when = fmt.Sprintf("%q", r.MountedWhen)
		}
		fmt.Fprintf(&b, "  { method: %q, path: %q, group: %q, auth: %q, permission: %s, stepUp: %t, mountedWhen: %s },\n",
			r.Method, fullPath(r), r.Group, r.Auth, perm, r.StepUp, when)
	}
	b.WriteString("]\n")
	return b.Bytes()
}

// errorCodesTS is the error catalog: every wire code, its status, and its
// English message (the default auth-ui shows).
func errorCodesTS() []byte {
	codes := errmodel.Codes()
	var b bytes.Buffer
	b.WriteString("// Generated by `go generate ./internal/httpapi` from AuthKit's error catalog. Do not edit.\n\n")
	b.WriteString("export type AuthErrorCode =\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "  | %q\n", c)
	}
	b.WriteString("\nexport const AUTH_ERROR_STATUS: Readonly<Record<AuthErrorCode, number>> = {\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "  %s: %d,\n", tsKey(string(c)), errmodel.Status(c))
	}
	b.WriteString("}\n\nexport const AUTH_ERROR_MESSAGES = {\n")
	for _, c := range codes {
		msg, _ := marshal(errmodel.Message(c))
		fmt.Fprintf(&b, "  %s: %s,\n", tsKey(string(c)), msg)
	}
	b.WriteString("} as const satisfies Record<AuthErrorCode, string>\n")
	return b.Bytes()
}
