// Command contract writes AuthKit's wire error codes, with their catalog
// statuses, to sdk/auth-ui's src/client/generated/error-codes.ts. Run it with
// go generate ./internal/errmodel.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"

	"github.com/open-rails/authkit/internal/errmodel"
)

func main() {
	out := flag.String("out", "sdk/auth-ui/src/client/generated", "output directory")
	flag.Parse()
	if err := os.WriteFile(filepath.Join(*out, "error-codes.ts"), errorCodesTS(), 0o644); err != nil {
		log.Fatal(err)
	}
}

func errorCodesTS() []byte {
	codes := errmodel.Codes()
	var b bytes.Buffer
	b.WriteString("// Generated by `go generate ./internal/errmodel` from AuthKit's error catalog. Do not edit.\n\n")
	b.WriteString("export type AuthErrorCode =\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "  | %q\n", c)
	}
	b.WriteString("\nexport const AUTH_ERROR_STATUS: Readonly<Record<AuthErrorCode, number>> = {\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "  %q: %d,\n", c, errmodel.Status(c))
	}
	b.WriteString("}\n")
	return b.Bytes()
}
